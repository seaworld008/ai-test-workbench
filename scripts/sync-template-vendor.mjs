#!/usr/bin/env node
// @ts-check
/**
 * Deterministically mirrors authoritative kernel sources (`src/kernel/**` + pure shared `src/core/*` helpers)
 * into standalone `templates/playwright-qa/support/` with version + source SHA-256 stamps (ADR-0002).
 *
 * Usage:
 *   node scripts/sync-template-vendor.mjs           # write/update vendored mirror
 *   node scripts/sync-template-vendor.mjs --check   # fail (exit 1) if any file is out of sync or stale
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { REPO_ROOT, SCHEMA_VERSIONS, WORKBENCH_VERSION } from '../src/app/index.mjs';

const KERNEL_SRC_DIR = path.join(REPO_ROOT, 'src', 'kernel');
const CORE_SRC_DIR = path.join(REPO_ROOT, 'src', 'core');
const TEMPLATE_QA_DIR = path.join(REPO_ROOT, 'templates', 'playwright-qa');
const TEMPLATE_SUPPORT_DIR = path.join(TEMPLATE_QA_DIR, 'support');

const STATIC_IMPORT_RE = /(?:import|export)\s+(?:[\s\S]*?\s+from\s+)?['"]([^'"]+)['"]|import\s*\(\s*['"]([^'"]+)['"]\s*\)/g;

/**
 * Automatically computes the transitive `src/core/*.mjs` dependency closure required
 * by `src/kernel/**` (always excluding `version.mjs`, which is generated separately).
 * @returns {string[]}
 */
function discoverVendoredCoreClosure() {
  /** @type {Set<string>} */
  const discovered = new Set();
  /** @type {string[]} */
  const queue = [];

  for (const rel of walkMjsRel(KERNEL_SRC_DIR)) {
    const abs = path.join(KERNEL_SRC_DIR, ...rel.split('/'));
    const text = fs.readFileSync(abs, 'utf8');
    for (const m of text.matchAll(STATIC_IMPORT_RE)) {
      const spec = m[1] || m[2];
      if (!spec || !spec.startsWith('.')) continue;
      const target = path.resolve(path.dirname(abs), spec);
      if (target.startsWith(CORE_SRC_DIR + path.sep) && target.endsWith('.mjs')) {
        const coreRel = path.relative(CORE_SRC_DIR, target).replace(/\\/g, '/');
        if (coreRel !== 'version.mjs' && !discovered.has(coreRel)) {
          discovered.add(coreRel);
          queue.push(target);
        }
      }
    }
  }

  while (queue.length > 0) {
    const abs = /** @type {string} */ (queue.shift());
    if (!fs.existsSync(abs)) continue;
    const text = fs.readFileSync(abs, 'utf8');
    for (const m of text.matchAll(STATIC_IMPORT_RE)) {
      const spec = m[1] || m[2];
      if (!spec || !spec.startsWith('.')) continue;
      const target = path.resolve(path.dirname(abs), spec);
      if (target.startsWith(CORE_SRC_DIR + path.sep) && target.endsWith('.mjs')) {
        const coreRel = path.relative(CORE_SRC_DIR, target).replace(/\\/g, '/');
        if (coreRel !== 'version.mjs' && !discovered.has(coreRel)) {
          discovered.add(coreRel);
          queue.push(target);
        }
      }
    }
  }

  return [...discovered].sort();
}

/**
 * @param {string} content
 * @returns {string}
 */
function sha256(content) {
  return crypto.createHash('sha256').update(content.replace(/\r\n/g, '\n'), 'utf8').digest('hex');
}

/**
 * @param {string} dir
 * @param {string} [base]
 * @param {string[]} [acc]
 * @returns {string[]}
 */
function walkMjsRel(dir, base = dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkMjsRel(full, base, acc);
    } else if (entry.isFile() && entry.name.endsWith('.mjs')) {
      acc.push(path.relative(base, full).replace(/\\/g, '/'));
    }
  }
  return acc.sort();
}

/**
 * Builds deterministic generated file content with source-SHA stamp (omits version banner so
 * patch bumps without kernel code edits never churn every vendored file).
 * @param {string} sourceText
 * @param {string} transformedBody
 * @returns {string}
 */
function wrapGeneratedBanner(sourceText, transformedBody) {
  const normalizedBody = transformedBody
    .replace(/\r\n/g, '\n')
    .replace(/^\s*\/\/\s*@ts-check\s*\n/, '');
  const header = [
    '// @generated by scripts/sync-template-vendor.mjs — DO NOT EDIT DIRECTLY',
    `// @source-sha256: ${sha256(sourceText)}`,
    '// @ts-nocheck',
    '',
  ].join('\n');
  return header + normalizedBody.trimStart();
}

/**
 * Rewrites `src/kernel/**` relative imports targeting `src/core/*` so vendored files
 * inside `templates/playwright-qa/support/` resolve `support/core/*` cleanly with zero external deps.
 * @param {string} relInKernel
 * @param {string} sourceText
 * @returns {string}
 */
function transformKernelSource(relInKernel, sourceText) {
  const depth = relInKernel.split('/').length - 1; // 0 for support/foo.mjs, 1 for support/gate/foo.mjs, 2 for support/gate/rules/foo.mjs
  const srcPrefix = '../'.repeat(depth + 1) + 'core/';
  const dstPrefix = (depth === 0 ? './' : '../'.repeat(depth)) + 'core/';
  let out = sourceText.replaceAll(`'${srcPrefix}`, `'${dstPrefix}`).replaceAll(`"${srcPrefix}`, `"${dstPrefix}`);
  // Strip type-only JSDoc @import references pointing to repo-only src/types/*.d.ts
  out = out.replace(/\/\*\*[\s\S]*?@import[\s\S]*?types\/[\s\S]*?\*\/\r?\n?/g, '');
  return out;
}

/**
 * Transforms a shared `src/core/*.mjs` file for standalone `templates/playwright-qa/support/core/`.
 * @param {string} sourceText
 * @returns {string}
 */
function transformCoreSource(sourceText) {
  return sourceText.replace(/\/\*\*[\s\S]*?@import[\s\S]*?types\/[\s\S]*?\*\/\r?\n?/g, '');
}

/**
 * Generates standalone `templates/playwright-qa/support/core/version.mjs` with stamped version constant.
 * @returns {string}
 */
function buildVendoredVersionModule() {
  const versionSrc = fs.readFileSync(path.join(CORE_SRC_DIR, 'version.mjs'), 'utf8');
  const body = [
    '// @ts-check',
    `export const WORKBENCH_VERSION = ${JSON.stringify(WORKBENCH_VERSION)};`,
    '',
    `export const SCHEMA_VERSIONS = Object.freeze(${JSON.stringify(SCHEMA_VERSIONS, null, 2)});`,
    '',
  ].join('\n');
  return wrapGeneratedBanner(`${versionSrc}\nversion=${WORKBENCH_VERSION}`, body);
}

/**
 * Computes the complete map of expected vendored files (absolute path -> desired UTF-8 contents).
 * @returns {Map<string, string>}
 */
export function buildExpectedVendorFiles() {
  /** @type {Map<string, string>} */
  const expected = new Map();
  /** @type {Record<string, string>} */
  const fileSourceShas = {};

  // 1. Vendored shared core closure under support/core/
  const coreClosure = discoverVendoredCoreClosure();
  for (const coreName of coreClosure) {
    const srcPath = path.join(CORE_SRC_DIR, ...coreName.split('/'));
    const raw = fs.readFileSync(srcPath, 'utf8');
    const transformed = transformCoreSource(raw);
    fileSourceShas[`core/${coreName}`] = `sha256:${sha256(raw)}`;
    expected.set(path.join(TEMPLATE_SUPPORT_DIR, 'core', ...coreName.split('/')), wrapGeneratedBanner(raw, transformed));
  }
  const vendoredVersionContent = buildVendoredVersionModule();
  expected.set(path.join(TEMPLATE_SUPPORT_DIR, 'core', 'version.mjs'), vendoredVersionContent);
  fileSourceShas['core/version.mjs'] = `sha256:${sha256(fs.readFileSync(path.join(CORE_SRC_DIR, 'version.mjs'), 'utf8'))}`;

  // 2. All authoritative kernel files (except package-only index.mjs entrypoint)
  const kernelRels = walkMjsRel(KERNEL_SRC_DIR).filter((rel) => rel !== 'index.mjs');
  for (const rel of kernelRels) {
    const srcPath = path.join(KERNEL_SRC_DIR, ...rel.split('/'));
    const raw = fs.readFileSync(srcPath, 'utf8');
    const transformed = transformKernelSource(rel, raw);
    const dstPath = path.join(TEMPLATE_SUPPORT_DIR, ...rel.split('/'));
    fileSourceShas[rel] = `sha256:${sha256(raw)}`;
    expected.set(dstPath, wrapGeneratedBanner(raw, transformed));
  }

  // 2b. Single centralized support/VERSION.json metadata manifest (`WU-03`)
  const sortedSourceShas = Object.fromEntries(
    Object.entries(fileSourceShas).sort(([a], [b]) => a.localeCompare(b))
  );
  expected.set(
    path.join(TEMPLATE_SUPPORT_DIR, 'VERSION.json'),
    JSON.stringify(
      {
        schemaVersion: 1,
        workbenchVersion: WORKBENCH_VERSION,
        gateKernelVersion: WORKBENCH_VERSION,
        sourceFiles: sortedSourceShas,
      },
      null,
      2
    ) + '\n'
  );

  // 3. Synchronize template package.json & package-lock.json version to root WORKBENCH_VERSION
  const tplPkgPath = path.join(TEMPLATE_QA_DIR, 'package.json');
  if (fs.existsSync(tplPkgPath)) {
    const tplPkg = JSON.parse(fs.readFileSync(tplPkgPath, 'utf8'));
    tplPkg.version = WORKBENCH_VERSION;
    expected.set(tplPkgPath, JSON.stringify(tplPkg, null, 2) + '\n');
  }

  const tplLockPath = path.join(TEMPLATE_QA_DIR, 'package-lock.json');
  if (fs.existsSync(tplLockPath)) {
    const tplLock = JSON.parse(fs.readFileSync(tplLockPath, 'utf8'));
    tplLock.version = WORKBENCH_VERSION;
    if (tplLock.packages && tplLock.packages['']) {
      tplLock.packages[''].version = WORKBENCH_VERSION;
    }
    expected.set(tplLockPath, JSON.stringify(tplLock, null, 2) + '\n');
  }

  return expected;
}

/**
 * Runs vendor sync or verification (`checkOnly: true`).
 * @param {{ checkOnly?: boolean }} [options]
 */
export function syncTemplateVendor(options = {}) {
  const checkOnly = Boolean(options.checkOnly);
  const expected = buildExpectedVendorFiles();

  /** @type {string[]} */
  const drifted = [];
  /** @type {string[]} */
  const stale = [];

  for (const [dstPath, desiredContent] of expected.entries()) {
    const current = fs.existsSync(dstPath) ? fs.readFileSync(dstPath, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current !== desiredContent) {
      drifted.push(path.relative(REPO_ROOT, dstPath).replace(/\\/g, '/'));
      if (!checkOnly) {
        fs.mkdirSync(path.dirname(dstPath), { recursive: true });
        fs.writeFileSync(dstPath, desiredContent, 'utf8');
      }
    }
  }

  // Detect any stale .mjs files inside templates/playwright-qa/support/
  const existingSupportMjs = walkMjsRel(TEMPLATE_SUPPORT_DIR).map((rel) =>
    path.join(TEMPLATE_SUPPORT_DIR, ...rel.split('/'))
  );
  for (const existingPath of existingSupportMjs) {
    if (!expected.has(existingPath)) {
      stale.push(path.relative(REPO_ROOT, existingPath).replace(/\\/g, '/'));
      if (!checkOnly) {
        fs.rmSync(existingPath, { force: true });
      }
    }
  }

  return {
    ok: drifted.length === 0 && stale.length === 0,
    totalFiles: expected.size,
    drifted,
    stale,
    version: WORKBENCH_VERSION,
  };
}

const isDirectMain =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isDirectMain) {
  const checkOnly = process.argv.includes('--check');
  const res = syncTemplateVendor({ checkOnly });
  if (checkOnly) {
    if (!res.ok) {
      console.error('[Vendor Sync DRIFT] templates/playwright-qa/support/ is out of sync with src/kernel/:');
      for (const f of res.drifted) console.error(`  [DRIFTED] ${f}`);
      for (const f of res.stale) console.error(`  [STALE]   ${f}`);
      console.error('Run "npm run sync:vendor" to regenerate the vendored template mirror.');
      process.exit(1);
    }
    const vendoredKernel = await import(
      `${pathToFileURL(path.join(TEMPLATE_SUPPORT_DIR, 'gate-kernel.mjs')).href}?check=${Date.now()}`
    );
    if (typeof vendoredKernel.runAuditForQaDir !== 'function' || vendoredKernel.GATE_KERNEL_VERSION !== WORKBENCH_VERSION) {
      console.error('[Vendor Sync SMOKE FAILED] Vendored support/gate-kernel.mjs failed standalone import verification.');
      process.exit(1);
    }
    console.log(`[Vendor Sync OK] All ${res.totalFiles} vendored template files match src/kernel/ (v${res.version}).`);
    process.exit(0);
  }
  const vendoredKernel = await import(
    `${pathToFileURL(path.join(TEMPLATE_SUPPORT_DIR, 'gate-kernel.mjs')).href}?sync=${Date.now()}`
  );
  if (typeof vendoredKernel.runAuditForQaDir !== 'function' || vendoredKernel.GATE_KERNEL_VERSION !== WORKBENCH_VERSION) {
    console.error('[Vendor Sync SMOKE FAILED] Vendored support/gate-kernel.mjs failed standalone import verification.');
    process.exit(1);
  }
  console.log(
    `[Vendor Sync] Synced ${res.totalFiles} file(s) (updated=${res.drifted.length}, removedStale=${res.stale.length}, v${res.version}).`
  );
}
