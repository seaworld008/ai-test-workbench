test('indexRepositorySource discovers frontend routes, broken imports, backend endpoints, and DB entities', () => {
  const repoDir = fs.mkdtempSync(path.join(os.tmpdir(), 'aitest-srcindex-'));
  try {
    fs.mkdirSync(path.join(repoDir, 'src', 'views', 'courses'), { recursive: true });
    fs.mkdirSync(path.join(repoDir, 'backend'), { recursive: true });
    fs.mkdirSync(path.join(repoDir, 'prisma'), { recursive: true });

    fs.writeFileSync(
      path.join(repoDir, 'src', 'views', 'courses', 'index.vue'),
      `<script>export default { mounted() { fetch('/api/courses'); } };</script>`,
      'utf8'
    );
    fs.writeFileSync(
      path.join(repoDir, 'src', 'router.js'),
      `export default [
        { path: '/courses', component: () => import('./views/courses/index') },
        { path: '/billing/legacy-invoices', component: () => import('./views/billing/missingInvoices') }
      ];`,
      'utf8'
    );
    fs.writeFileSync(
      path.join(repoDir, 'backend', 'CourseController.java'),
      `@RequestMapping("/api")
      @TableName("courses")
      public class CourseController {
        @GetMapping("/courses")
        public void list() {}
      }`,
      'utf8'
    );
    fs.writeFileSync(
      path.join(repoDir, 'prisma', 'schema.prisma'),
      `model Enrollment {
        id Int @id
      }`,
      'utf8'
    );

    const idx = indexRepositorySource(repoDir);
    assert.ok(idx.frontendRoutes.some((r) => r.route === '/courses' && r.file === 'src/views/courses/index.vue'));
    assert.equal(idx.brokenRouteImports.length, 1);
    assert.equal(idx.brokenRouteImports[0].route, '/billing/legacy-invoices');
    assert.ok(idx.backendEndpoints.some((e) => e.path === '/api/courses' && e.framework === 'spring'));
    assert.ok(idx.dbEntities.some((d) => d.table === 'courses'));
    assert.ok(idx.dbEntities.some((d) => d.table === 'Enrollment'));
  } finally {
    fs.rmSync(repoDir, { recursive: true, force: true });
  }
});

test('mergeLivingCodeMap evolves across revisions and syncImpactMapFromCodeMap preserves manual rules', async () => {
  const repoDir = fs.mkdtempSync(path.join(os.tmpdir(), 'aitest-codemap-evolve-'));
  try {
    fs.mkdirSync(path.join(repoDir, 'src', 'views'), { recursive: true });
    fs.writeFileSync(path.join(repoDir, 'src', 'views', 'Home.vue'), `<script>fetch('/api/health');</script>`, 'utf8');
    fs.writeFileSync(
      path.join(repoDir, 'src', 'router.js'),
      `export default [{ path: '/', component: () => import('./views/Home') }, { path: '/courses', component: () => import('./views/Home') }];`,
      'utf8'
    );

    await runCli(['init', '--name', 'evolve-app', '--target', repoDir, '--skip-install', '--loop', 'none']);
    const qaDir = path.join(repoDir, 'qa');

    // Add a custom manual rule in impact-map.json
    const impactPath = path.join(qaDir, 'impact-map.json');
    fs.writeFileSync(
      impactPath,
      JSON.stringify({ rules: [{ match: ['custom/**'], specs: ['tests/e2e/home.spec.ts'] }] }, null, 2),
      'utf8'
    );

    const sync1 = syncLivingCodeMap(qaDir, { lang: 'en', repoDir });
    assert.equal(sync1.revision, 1);
    assert.ok(sync1.impactSync.manualRulesCount >= 1);
    assert.ok(fs.existsSync(sync1.systemMapMdPath));

    // Add an explored runtime route + passing results.json -> Revision 2 accumulates
    fs.mkdirSync(path.join(qaDir, 'reports'), { recursive: true });
    fs.writeFileSync(
      path.join(qaDir, 'reports', 'system-topology.json'),
      JSON.stringify({
        baseURL: 'http://127.0.0.1:4000',
        portals: [{ name: 'Tenant Workspace', mode: 'tenant', id: 101 }],
        pages: [{ route: '/orders', archetype: 'crud-table', tableHeaders: ['订单编号'] }],
      }),
      'utf8'
    );

    const sync2 = syncLivingCodeMap(qaDir, { lang: 'zh', repoDir });
    assert.equal(sync2.revision, 2);
    const mapJson = JSON.parse(fs.readFileSync(sync2.codeMapPath, 'utf8'));
    assert.ok(mapJson.routes['/orders']);
    assert.ok(mapJson.routes['/courses']);
    assert.equal(mapJson.history.length, 2);

    const md = generateLivingSystemMapMarkdown(mapJson, 'zh');
    assert.match(md, /Revision v2/);
    assert.match(md, /\/orders/);

    // Verify manual rule survived impact-map sync
    const finalImpact = JSON.parse(fs.readFileSync(impactPath, 'utf8'));
    assert.ok(finalImpact.rules.some((r) => !r.autoGenerated && r.match[0] === 'custom/**'));
  } finally {
    fs.rmSync(repoDir, { recursive: true, force: true });
  }
});

test('generateDiagnosticsMarkdown correlates CodeMap source files and captured traceIds', () => {
  const qaDir = fs.mkdtempSync(path.join(os.tmpdir(), 'aitest-diag-link-'));
  try {
    fs.mkdirSync(path.join(qaDir, 'knowledge'), { recursive: true });
    fs.mkdirSync(path.join(qaDir, 'reports'), { recursive: true });
    fs.writeFileSync(
      path.join(qaDir, 'knowledge', 'code-map.json'),
      JSON.stringify({
        routes: {
          '/courses': {
            route: '/courses',
            frontendFile: 'src/views/Courses.vue',
            linkedBackendFiles: ['backend/CourseController.java'],
            linkedDbTables: ['courses'],
            linkedApis: ['/api/courses'],
            coveringSpecs: ['tests/e2e/courses.spec.ts'],
          },
        },
      }),
      'utf8'
    );

    const resultsPath = path.join(qaDir, 'reports', 'results.json');
    const guardAttachment = Buffer.from(
      JSON.stringify({
        traceIds: ['x-trace-id:trace-987654321'],
        timeWindow: { startedAt: '2026-11-23T10:00:00Z', finishedAt: '2026-11-23T10:00:02Z' },
      }),
      'utf8'
    ).toString('base64');

    fs.writeFileSync(
      resultsPath,
      JSON.stringify({
        suites: [
          {
            file: 'e2e/courses.spec.ts',
            specs: [
              {
                title: 'load courses fails on 500',
                file: 'e2e/courses.spec.ts',
                line: 10,
                tests: [
                  {
                    projectName: 'e2e',
                    status: 'unexpected',
                    results: [
                      {
                        error: { message: 'Same-origin 5xx on /api/courses' },
                        attachments: [{ name: 'workbench-runtime-guard.json', body: guardAttachment }],
                      },
                    ],
                  },
                ],
              },
            ],
          },
        ],
      }),
      'utf8'
    );

    const out = generateDiagnosticsMarkdown(qaDir, resultsPath);
    assert.equal(out.failureCount, 1);
    assert.match(out.markdown, /trace-987654321/);
    assert.match(out.markdown, /src\/views\/Courses\.vue/);
    assert.match(out.markdown, /CourseController\.java/);
    assert.match(out.markdown, /SELECT COUNT\(\*\) FROM courses/);
  } finally {
    fs.rmSync(qaDir, { recursive: true, force: true });
  }
});
